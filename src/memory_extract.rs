//! What the memory reader reads: a soul's mirrors through the same adapters
//! the graph uses (Claude Code, Antigravity, claude.ai): AUTHORED prose, plus
//! each tool call as one line with how it came out (#27), never the output
//! itself and never thinking; each turn labelled with who spoke it.
//!
//! The model that writes the memory is in `writer`.

use crate::SourceKind;
use anyhow::Result;
use serde_json::{json, Value};
use std::collections::HashMap;
use std::path::{Path, PathBuf};

/// The most of one turn a reader is shown: longer turns keep head and tail.
const TURN_CHARS: usize = 4_000;

// ───────────────────────────── sources ─────────────────────────────

/// One turn's prose, ready to read.
#[derive(Debug, Clone)]
pub struct ProseTurn {
    pub id: String,
    pub ts: String,
    /// "user" (the human's side of the session) or "assistant" (the soul),
    /// whatever the harness calls them.
    pub role: String,
    pub text: String,
    /// The peer soul that sent this user turn, when the sender's own
    /// transcript shows the send (see `peers`).
    pub peer: Option<crate::peers::Sent>,
}

/// A conversation's turns in order, from one source.
#[derive(Debug)]
pub struct Conversation {
    pub source: &'static str,
    pub id: String,
    /// Where it happened, as far as the source says: a working directory, or
    /// a claude.ai chat's title. Tells the model which project it is reading.
    pub place: String,
    pub turns: Vec<ProseTurn>,
}

pub(crate) fn authored(e: &crate::Event) -> String {
    let Some(text) = &e.text else {
        return String::new();
    };
    if e.text_provenance.is_empty() {
        return text.clone();
    }
    e.text_provenance
        .iter()
        .filter(|s| s.kind == SourceKind::Authored)
        .filter_map(|s| text.get(s.start..s.end))
        .collect::<Vec<_>>()
        .join("\n")
}

/// Claude Code's compaction summary arrives as a user turn that opens with
/// this sentence. It is a model's summary of earlier turns that are already
/// read on their own: a copy of a copy, never a source (4m41th34's check,
/// 2026-10-05).
const COMPACTION_OPENING: &str = "This session is being continued from a previous conversation";

/// Harness records that arrive as user turns but are no one's words: slash
/// commands and their output, background-task and system notices, skill
/// bodies, fork and workflow prompts, interruption markers. Matched on how
/// the turn starts (counted over W4R3Z, spaceGOAT and lUX, 2026-10-13).
const HARNESS_OPENINGS: &[&str] = &[
    "<task-notification",
    "<command-name",
    "<command-message",
    "<command-args",
    "<local-command-stdout",
    "<local-command-stderr",
    "<local-command-caveat",
    "Caveat: The messages below were generated by the user while running local commands",
    "<system-reminder",
    "<bash-stdout",
    "<bash-stderr",
    "<fork-boilerplate",
    "[Workflow harness",
    "[SYSTEM NOTIFICATION",
    "[Request interrupted by user",
    "Base directory for this skill",
    "[earlier conversation truncated",
    "[Usage limit approaching",
];

/// A user turn's own words, or empty when it is harness noise. `<bash-input>`
/// is the human running a shell command: kept, said plainly. A slash command
/// alone on its line (`/compact`) is the harness's.
fn human_words(t: &str) -> String {
    let t = strip_reminders(t);
    let s = t.trim_start();
    if HARNESS_OPENINGS.iter().any(|o| s.starts_with(o)) {
        return String::new();
    }
    if let Some(cmd) = s
        .strip_prefix("<bash-input>")
        .and_then(|r| r.split("</bash-input>").next())
    {
        return format!("(ran in the shell) {}", cmd.trim());
    }
    if s.starts_with('/') && !s.contains(char::is_whitespace) {
        return String::new();
    }
    t
}

/// True when a user turn's text is a person's own typed words: not harness
/// noise, not a compaction summary.
pub(crate) fn persons_own(t: &str) -> bool {
    !t.trim_start().starts_with(COMPACTION_OPENING) && !human_words(t).trim().is_empty()
}

/// Text with every `<system-reminder>…</system-reminder>` block removed:
/// the harness's notes riding inside a human turn.
fn strip_reminders(t: &str) -> String {
    let mut out = String::new();
    let mut rest = t;
    while let Some(i) = rest.find("<system-reminder>") {
        out += &rest[..i];
        match rest[i..].find("</system-reminder>") {
            Some(j) => rest = &rest[i + j + "</system-reminder>".len()..],
            None => {
                rest = "";
            }
        }
    }
    out += rest;
    out
}

/// An Antigravity USER_INPUT's own words: the `<USER_REQUEST>` body. The
/// `<ADDITIONAL_METADATA>` (local time) and `<USER_SETTINGS_CHANGE>` (model
/// switch) blocks around it are the harness's.
fn agy_request(t: &str) -> String {
    match t.split_once("<USER_REQUEST>") {
        Some((_, rest)) => rest
            .split("</USER_REQUEST>")
            .next()
            .unwrap_or("")
            .trim()
            .to_string(),
        None => t.trim().to_string(),
    }
}

/// One tool call as the writer reads it, with how it came out (#27):
/// `[ran: cargo test → test result: ok. 96 passed (+4 lines)]`. A read or an
/// edit says nothing of its output unless it failed: the file's text is not
/// news. One line, never the output itself.
fn action_line(a: &crate::Action, o: Option<&crate::Outcome>) -> String {
    use crate::ActionKind::*;
    let verb = match a.kind {
        Ran => "ran",
        Read => "read",
        Edited => "edited",
        Searched => "searched",
        Listed => "listed",
        Subagent => "asked a subagent",
        Fetched => "fetched",
        Other => "used",
    };
    let result = match o {
        Some(o) if o.failed => format!(" → failed: {}", o.first),
        // Its answer arrives later, as a message; this is only the receipt.
        Some(o) if a.kind == Subagent && o.first.starts_with("Async agent launched") => {
            " → started in the background".into()
        }
        Some(_) if matches!(a.kind, Read | Edited | Listed) => String::new(),
        Some(o) if o.first.is_empty() => " → no output".into(),
        Some(o) if o.lines > 0 => format!(" → {} (+{} lines)", o.first, o.lines),
        Some(o) => format!(" → {}", o.first),
        None => String::new(),
    };
    format!("[{verb}: {}{result}]", a.target)
}

fn to_turns(events: &[crate::Event], source: &str) -> Vec<ProseTurn> {
    let results: HashMap<&str, &crate::Outcome> = events
        .iter()
        .flat_map(|e| e.outcomes.iter())
        .map(|o| (o.id.as_str(), o))
        .collect();
    let turns: Vec<ProseTurn> = events
        .iter()
        .filter_map(|e| {
            // One vocabulary for both harnesses. Antigravity says
            // USER_EXPLICIT / MODEL / SYSTEM; its SYSTEM records are task
            // results, scheduled-task firings and compaction checkpoints,
            // never anyone's words (4RX, 2026-10-13: read as the soul's own
            // turns, they made its Gemini session look like a stranger).
            let role = match (source, e.role.as_str()) {
                ("agy", "USER_EXPLICIT") => "user",
                ("agy", "MODEL") => "assistant",
                ("agy", _) => return None,
                (_, r) => r,
            };
            let mut t = authored(e);
            if t.trim_start().starts_with(COMPACTION_OPENING) {
                t.clear();
            }
            if role == "user" {
                t = if source == "agy" {
                    agy_request(&t)
                } else {
                    human_words(&t)
                };
            }
            // What the soul did, beside what it said: a check it ran is part
            // of its life, and without this line the writer can only see the
            // claim (#27).
            if role == "assistant" && !e.actions.is_empty() {
                let did: Vec<String> = e
                    .actions
                    .iter()
                    .map(|a| action_line(a, results.get(a.id.as_str()).copied()))
                    .collect();
                if !t.trim().is_empty() {
                    t.push('\n');
                }
                t.push_str(&did.join("\n"));
            }
            Some(ProseTurn {
                id: e.event_id.clone(),
                ts: e.timestamp.clone()?,
                role: role.to_string(),
                text: t,
                peer: None,
            })
        })
        .collect();
    fold_actions(turns)
}

/// Claude Code writes each tool call as its own record, so a soul that says
/// one thing and then runs ten commands makes eleven turns. Tool-call lines
/// never make a turn of their own: they join the soul's turn of words just
/// before them, or, when the human spoke last, the soul's next turn of words
/// (its reply, after the work). With neither, they are dropped. So every turn
/// keeps an id the memory has already seen: reading commands must never make
/// a soul's past look unread and get relived (#27: a first build made 4,142 of
/// lUX's old turns new).
fn fold_actions(turns: Vec<ProseTurn>) -> Vec<ProseTurn> {
    let mut out: Vec<ProseTurn> = Vec::new();
    let mut waiting: Vec<String> = Vec::new();
    for mut t in turns {
        let only_actions = t.role == "assistant"
            && !t.text.trim().is_empty()
            && t.text
                .lines()
                .all(|l| l.starts_with('[') && l.ends_with(']'));
        if only_actions {
            let last = out.iter_mut().rev().find(|x| !x.text.trim().is_empty());
            match last {
                Some(l) if l.role == "assistant" && waiting.is_empty() => {
                    l.text.push('\n');
                    l.text.push_str(&t.text);
                }
                _ => waiting.push(t.text),
            }
            continue;
        }
        if !t.text.trim().is_empty() {
            if t.role == "assistant" && !waiting.is_empty() {
                t.text = format!("{}\n{}", waiting.join("\n"), t.text);
            }
            waiting.clear();
        }
        out.push(t);
    }
    out
}

/// Every conversation in a soul's mirrors.
pub fn conversations(repo: &Path) -> Result<Vec<Conversation>> {
    let mut out = Vec::new();
    let cc = repo.join(crate::sync::TRANSCRIPTS_SUBDIR);
    if cc.is_dir() {
        for p in crate::sync::walk_jsonl(&cc) {
            // A subagent's or workflow's transcript is not the soul's own
            // life. OptMem: a subagent must never write memory — its notes
            // would arrive duplicated and wrong.
            if p.components().any(|c| c.as_os_str() == "subagents") {
                continue;
            }
            let Ok(s) = std::fs::read_to_string(&p) else {
                continue;
            };
            let Ok(ev) = crate::adapter::parse_transcript(&s) else {
                continue;
            };
            let id = p
                .strip_prefix(&cc)
                .unwrap_or(&p)
                .to_string_lossy()
                .into_owned();
            let place = first_cwd(&s)
                .map(|c| format!("working directory {c}"))
                .unwrap_or_default();
            out.push(Conversation {
                source: "claude-code",
                id,
                place,
                turns: to_turns(&ev, "claude-code"),
            });
        }
    }
    let agy = repo.join(crate::sync::AGY_TRANSCRIPTS_SUBDIR);
    if agy.is_dir() {
        for e in std::fs::read_dir(&agy)?.flatten() {
            let p = e.path();
            if p.extension().and_then(|x| x.to_str()) != Some("jsonl") {
                continue;
            }
            let id = p
                .file_stem()
                .unwrap_or_default()
                .to_string_lossy()
                .into_owned();
            let Ok(s) = std::fs::read_to_string(&p) else {
                continue;
            };
            let Ok(parsed) = crate::agy::parse_transcript(&s, &id) else {
                continue;
            };
            out.push(Conversation {
                source: "agy",
                id,
                place: String::new(),
                turns: to_turns(&parsed.events, "agy"),
            });
        }
    }
    let shelf = repo.join(crate::sync::CLAUDE_AI_SUBDIR);
    if shelf.is_dir() {
        let mut best: HashMap<String, (String, crate::claude_ai::Conversation)> = HashMap::new();
        let mut exports: Vec<PathBuf> = std::fs::read_dir(&shelf)?
            .flatten()
            .map(|e| e.path())
            .filter(|p| crate::claude_ai::is_export_dir(p))
            .collect();
        exports.sort();
        for e in exports {
            for c in crate::claude_ai::read_conversations(&e)? {
                let k = crate::claude_ai::version_key(&c);
                if best.get(&c.uuid).is_none_or(|(bk, _)| k > *bk) {
                    best.insert(c.uuid.clone(), (k, c));
                }
            }
        }
        for (id, (_, c)) in best {
            let place = if c.name.is_empty() {
                "a Claude desktop chat".to_string()
            } else {
                format!("a Claude desktop chat titled {:?}", c.name)
            };
            out.push(Conversation {
                source: "claude.ai",
                id,
                place,
                turns: to_turns(&crate::claude_ai::conversation_events(&c), "claude.ai"),
            });
        }
    }
    Ok(out)
}

